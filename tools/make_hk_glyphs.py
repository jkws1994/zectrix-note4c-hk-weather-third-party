"""Build the NOTE4C's offline HK glyphs: python make_hk_glyphs.py NotoSansHK.ttf.

Use NotoSansHK[wght].ttf from google/fonts, ofl/notosanshk (SIL OFL).
The checked-in bitmap data is ready to build. Regeneration requires Pillow.
"""
import hashlib
import re
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

src = Path(__file__).resolve().parents[1] / "src"
font_file = Path(sys.argv[1])
text = "".join((src / file).read_text() for file in ("screen.cpp", "district.cpp", "weather.cpp"))
text += (src / "main.cpp").read_text().split("Selection selectLocation(", 1)[1]
characters = sorted(set(re.findall(r"[^\x00-\x7f]", text)))
lines = [
    "// Generated by tools/make_hk_glyphs.py using Noto Sans HK (SIL OFL).",
    "// Source TTF SHA-256 " + hashlib.sha256(font_file.read_bytes()).hexdigest(),
    "struct HKFont { int size, ascent; const uint8_t* bits; };",
    "static constexpr uint16_t hkCodes[]={",
    ",".join(hex(ord(c)) for c in characters),
    "};",
]

for size in (12, 14, 18, 24, 32):
    font = ImageFont.truetype(str(font_file), size)
    font.set_variation_by_axes([480 if size <= 18 else 600])
    ascent = round(size * .88)
    lines.append(f"static constexpr uint8_t hkBits{size}[]={{")
    for char in characters:
        # Pad while rasterising, then pull any overhang into its cell.
        layer = Image.new("L", (size + 8, size + 8))
        ImageDraw.Draw(layer).text((4, 4 + ascent), char, anchor="ls", font=font, fill=255)
        layer = layer.point(lambda p: 255 if p >= 100 else 0, "1")
        bounds = layer.getbbox()
        if not bounds:
            raise ValueError(f"Empty glyph {char!r}")
        left, top, right, bottom = bounds
        x = max(right - size, min(4, left))
        y = max(bottom - size, min(4, top))
        if right - left > size or bottom - top > size:
            raise ValueError(f"Glyph exceeds cell: {char!r} at {size}px")
        data = layer.crop((x, y, x + size, y + size)).tobytes()
        lines.append(",".join(f"0x{b:02x}" for b in data) + ",")
    lines.extend(["};", f"static constexpr HKFont hk{size}={{{size},{ascent},hkBits{size}}};"])

(src / "hk_glyphs.inc").write_text("\n".join(lines) + "\n")
print(f"Embedded {len(characters)} HK characters at five sizes.")
